// Copies the pure business modules of the TITAN website into the Android app, unchanged, so both clients apply the
// same effort/XP, sport catalogue, progression, records and campaign rules (the server stays the authority).
// Usage: node scripts/sync-web-core.mjs <web checkout> <git sha of that checkout>
// It also regenerates src/core/icons.generated.ts from js/app/icons.js and the manifest checked by the unit tests.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import vm from "node:vm";

const [webRoot, sha] = process.argv.slice(2);
if (!webRoot || !sha) throw new Error("usage: node scripts/sync-web-core.mjs <web checkout> <sha>");
const target = new URL("../src/core/web/", import.meta.url);

// Load order matters: each module reads the previous ones from the global object.
export const MODULES = [
  "js/core/format.js",
  "js/training-store.js",
  "js/core/effort.js",
  "js/core/sports-catalog.js",
  "js/core/sports.js",
  "js/sport-insights.js",
  "js/core/progress.js",
  "js/core/questions.js",
  "js/renaissance-catalog.js",
  "js/renaissance-engine.js",
  "js/core/campaign-quests.js",
  "js/core/campaign-encounters.js",
  "js/core/sport-navigation.js",
  "js/core/gpx.js",
];

const manifest = { source: "Theo25460/TITAN_V0.5", sha, files: {} };
for (const rel of MODULES) {
  const source = readFileSync(join(webRoot, rel), "utf8");
  const name = rel.split("/").pop();
  writeFileSync(new URL(name, target), source);
  manifest.files[name] = createHash("sha256").update(source).digest("hex");
}
writeFileSync(new URL("manifest.json", target), JSON.stringify(manifest, null, 2) + "\n");

// Icons: evaluate the website icon set and keep its SVG children as data for react-native-svg.
const sandbox = { module: { exports: {} } };
vm.runInNewContext(readFileSync(join(webRoot, "js/app/icons.js"), "utf8"), sandbox);
const paths = sandbox.module.exports.paths;
if (!paths) throw new Error("icons.js: icon paths not exposed");
const icons = {};
for (const [name, svg] of Object.entries(paths)) {
  icons[name] = [...svg.matchAll(/<(path|circle|rect|line|polyline|ellipse)\b([^>]*)\/?>/g)].map(([, tag, attrs]) => {
    const props = {};
    for (const [, k, v] of attrs.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) props[k.replace(/-([a-z])/g, (_, c) => c.toUpperCase())] = v;
    return [tag, props];
  });
}
const body = `/* Generated by scripts/sync-web-core.mjs from js/app/icons.js (${sha}). Do not edit by hand. */
export type IconElement = ["path" | "circle" | "rect" | "line" | "polyline" | "ellipse", Record<string, string>];
export const ICONS = ${JSON.stringify(icons)} as const satisfies Record<string, readonly IconElement[]>;
export type IconName = keyof typeof ICONS;
`;
writeFileSync(new URL("../src/core/icons.generated.ts", import.meta.url), body);
console.log(`${MODULES.length} modules, ${Object.keys(icons).length} icons from ${sha}`);
