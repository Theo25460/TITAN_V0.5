// Builds the TITAN sport icon set from tools/sport-icons/glyphs.mjs.
// Writes:
//   js/app/sport-icons.js                    the glyphs, read by titanIcon() on the web and by mobile/scripts/sync-web-core.mjs
//   docs/design/sport-icons/registry.json    every sport of the catalogue → its glyph, family, status (the registry)
// Usage: node tools/sport-icons/build.mjs  (then: cd mobile && node scripts/sync-web-core.mjs .. $(git rev-parse HEAD))
import { mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { GLYPHS } from "./glyphs.mjs";

const require = createRequire(import.meta.url);
const root = new URL("../../", import.meta.url);

// Shorter numbers: two decimals at most, no leading zero.
const tidy = (svg) =>
  svg.replace(/-?\d*\.\d+/g, (n) => String(Math.round(Number(n) * 100) / 100).replace(/^(-?)0\./, "$1.")).replace(/\s+/g, " ").replace(/ \/>/g, "/>");

const names = Object.keys(GLYPHS).sort();
for (const n of names) {
  if (!/^(sport|family)-[a-z0-9]+(-[a-z0-9]+)*$/.test(n)) throw new Error(`glyph name ${n}: sport-<kebab> or family-<kebab>`);
  if (!GLYPHS[n] || !/<(path|circle|rect|ellipse)\b/.test(GLYPHS[n])) throw new Error(`glyph ${n} is empty`);
  if (/<g\b|<polygon|<text|<use|style=/.test(GLYPHS[n])) throw new Error(`glyph ${n}: only path, circle, rect, ellipse (Android draws these)`);
}
const body = names.map((n) => `    ${JSON.stringify(n)}: ${JSON.stringify(tidy(GLYPHS[n]))},`).join("\n");
const js = `/* TITAN — sport icons. Generated by tools/sport-icons/build.mjs from tools/sport-icons/glyphs/*. Do not edit by hand.
   ${names.filter((n) => n.startsWith("sport-")).length} sport glyphs and ${names.filter((n) => n.startsWith("family-")).length} family marks on the 24 grid of js/app/icons.js; the system is described in
   docs/design/SPORT_ICONS.md. Which sport uses which glyph is decided by TitanSports.iconOf (js/core/sports.js). */
(function (root) {
  "use strict";
  const paths = {
${body}
  };
  root.TITAN_SPORT_ICONS = paths;
  if (typeof module !== "undefined") module.exports = { paths };
})(typeof window === "undefined" ? globalThis : window);
`;
writeFileSync(new URL("js/app/sport-icons.js", root), js);

// The registry: one line per sport of the offline catalogue.
require(new URL("js/core/sports-catalog.js", root).pathname);
const Sports = require(new URL("js/core/sports.js", root).pathname);
const rows = (globalThis.TITAN_SPORTS_SNAPSHOT || []).map(([id, label]) => ({ id, label, family: Sports.familyOf(id), glyph: Sports.iconOf(id) }));
const users = {};
for (const r of rows) (users[r.glyph] ||= []).push(r.id);
const registry = {
  generated: "tools/sport-icons/build.mjs",
  system: "docs/design/SPORT_ICONS.md",
  glyphs: names.length,
  sports: rows.length,
  ownGlyph: rows.filter((r) => users[r.glyph].length === 1).length,
  shared: Object.fromEntries(Object.entries(users).filter(([, ids]) => ids.length > 1)),
  families: Object.fromEntries(Object.entries(Sports.FAMILY_ICON)),
  rows: rows.map((r) => ({ ...r, status: users[r.glyph].length > 1 ? "shared" : "own" })),
};
mkdirSync(new URL("docs/design/sport-icons/", root), { recursive: true });
writeFileSync(new URL("docs/design/sport-icons/registry.json", root), JSON.stringify(registry, null, 2) + "\n");
const missing = rows.filter((r) => !GLYPHS[r.glyph]);
if (missing.length) throw new Error(`no glyph for ${missing.map((r) => `${r.id} → ${r.glyph}`).join(", ")}`);
console.log(`${names.length} glyphs, ${js.length} bytes; ${rows.length} sports, ${registry.ownGlyph} with their own glyph, ${Object.keys(registry.shared).length} shared glyphs`);
