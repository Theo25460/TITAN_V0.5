const rows = JSON.parse(readFileSync("tools/data/sports-catalog.json", "utf8"));
if (process.argv.includes("--sql")) {
  const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
  const values = rows
    .filter(([id, label]) => LABELS[id] && LABELS[id] !== label)
    .map(([id]) => `(${q(id)}, ${q(LABELS[id])})`);
  process.stdout.write(
    `update public.sports s set label = v.label, updated_at = now()\nfrom (values\n  ${values.join(",\n  ")}\n) as v(id, label)\nwhere s.id = v.id and s.label is distinct from v.label;\n`,
  );
} else {
  const compact = rows.map(([id, label, unit, cat, profile, aliases, sort]) => [id, LABELS[id] || label, unit, cat, profile, aliases, sort]);
  const body = `/* Generated by tools/build-sports-catalog.mjs — offline snapshot of public.sports. Do not edit by hand. */
(function (root) {
  "use strict";
  const ROWS = ${JSON.stringify(compact)};
  root.TITAN_SPORTS_SNAPSHOT = ROWS;
  if (typeof module !== "undefined") module.exports = ROWS;
})(typeof window !== "undefined" ? window : globalThis);
`;
  writeFileSync("js/core/sports-catalog.js", body);
  console.log(`js/core/sports-catalog.js: ${compact.length} sports, ${Object.keys(LABELS).length} clean labels`);
}
