#!/usr/bin/env bash
# Measure, on a throwaway local Postgres built like tools/db/test-migrations.sh (production structure snapshot, no data), the
# function fingerprints (FINGERPRINT_SQL of tools/db/build-production-bundle.mjs) that production must show before and after each
# canonical V2.0 package (tools/db/v2-canonical.mjs). Writes tools/db/v2-fingerprints.json; the generator reads it.
# Usage: tools/db/measure-v2-fingerprints.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PGBIN="${PGBIN:-$(ls -d /usr/lib/postgresql/*/bin 2>/dev/null | sort -V | tail -1)}"
PORT="${PGPORT_TEST:-54329}"
DIR="${TITAN_PG_DIR:-/tmp/titan-pg}"
DB="titan_test_fp_$$"
if ! "$PGBIN/pg_isready" -h "$DIR" -p "$PORT" >/dev/null 2>&1; then
  rm -rf "$DIR"; mkdir -p "$DIR"
  id postgres >/dev/null 2>&1 || useradd -m postgres
  chown postgres:postgres "$DIR"
  su postgres -c "$PGBIN/initdb -D $DIR/data -A trust -U postgres >/dev/null && $PGBIN/pg_ctl -D $DIR/data -o '-p $PORT -k $DIR' -l $DIR/log.txt start >/dev/null"
  sleep 2
fi
PSQL=("$PGBIN/psql" -h "$DIR" -p "$PORT" -U postgres -v ON_ERROR_STOP=1 -q -X)
"${PSQL[@]}" -d postgres -c "create database $DB" >/dev/null
trap '"${PSQL[@]}" -d postgres -c "drop database if exists $DB" >/dev/null 2>&1 || true' EXIT
FP_SQL="$(node --input-type=module -e "process.argv=['node','x','--bundle','v131'];const m=await import('$ROOT/tools/db/build-production-bundle.mjs');console.log(m.FINGERPRINT_SQL)")"
measure() { "${PSQL[@]}" -d "$DB" -At -F '|' -c "$FP_SQL"; }
"${PSQL[@]}" -d "$DB" -f "$ROOT/tools/db/supabase-shim.sql" >/dev/null
for f in "$ROOT"/tools/db/baseline/*.sql; do "${PSQL[@]}" -d "$DB" -f "$f" >/dev/null; done
HEAD="$(cat "$ROOT/tools/db/production-head.txt")"
UNTILS="$(node --input-type=module -e "const m=await import('$ROOT/tools/db/v2-canonical.mjs');const {existsSync}=await import('node:fs');for(const b of m.BUNDLES){const p=b.migrations.filter(x=>existsSync('$ROOT/supabase/migrations/'+x.version+'_'+x.old.slice(15)));if(p.length===b.migrations.length)console.log(b.name+' '+p.at(-1).version)}")"
OUT="{"
sep=""
for f in "$ROOT"/supabase/migrations/*.sql; do
  v="$(basename "$f" | cut -d_ -f1)"
  [[ "$v" < "20261005150000" ]] && continue
  "${PSQL[@]}" -d "$DB" -f "$f" >/dev/null
  if [[ "$v" == "$HEAD" ]]; then
    OUT+="$sep\"$v\": {$(measure | awk -F'|' '{printf "%s\"%s\": [%s, \"%s\", \"%s\"]", (NR>1?", ":""), $1, $2, $3, $4}')}"; sep=", "
  fi
  while read -r name until; do
    [[ -z "$name" ]] && continue
    if [[ "$v" == "$until" ]]; then
      OUT+="$sep\"$v\": {$(measure | awk -F'|' '{printf "%s\"%s\": [%s, \"%s\", \"%s\"]", (NR>1?", ":""), $1, $2, $3, $4}')}"; sep=", "
      echo "  · $name ends at $v" >&2
    fi
  done <<< "$UNTILS"
done
OUT+="}"
node -e "const o=JSON.parse(process.argv[1]);require('fs').writeFileSync(process.argv[2],JSON.stringify({_:'Generated by tools/db/measure-v2-fingerprints.sh on a clean replica: function fingerprints after the given migration version (production head, then the end of each canonical package).',after:o},null,2)+'\n')" "$OUT" "$ROOT/tools/db/v2-fingerprints.json"
echo "tools/db/v2-fingerprints.json written"
